const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('wave', {
  platform: 'electron',
  canAnalyzeAudio: true,
  canUpload: true,
  files: {
    write: (name, data) => ipcRenderer.invoke('wave:files:write', name, data),
    read: (name) => ipcRenderer.invoke('wave:files:read', name),
    remove: (name) => ipcRenderer.invoke('wave:files:remove', name),
    list: () => ipcRenderer.invoke('wave:files:list'),
  },
  fetchBytes: (url) => ipcRenderer.invoke('wave:fetch-bytes', url),
  setNetworkForTest: (up) => ipcRenderer.send('wave:test:network', up),
  testMode: ipcRenderer.sendSync('wave:test-mode'),
  request: (req) => ipcRenderer.invoke('ym:request', req),
  hasToken: () => ipcRenderer.invoke('ym:token:has'),
  setToken: (value) => ipcRenderer.invoke('ym:token:set', value),
  login: (lang) => ipcRenderer.invoke('ym:login', lang),
  hasDiskToken: () => ipcRenderer.invoke('disk:token:has'),
  setDiskToken: (value) => ipcRenderer.invoke('disk:token:set', value),
  diskLogin: (lang) => ipcRenderer.invoke('disk:login', lang),
  lan: {
    start: (device) => ipcRenderer.invoke('lan:start', device),
    stop: () => ipcRenderer.invoke('lan:stop'),
    send: (to, text) => ipcRenderer.send('lan:send', { to, text }),
    onMessage: (cb) => ipcRenderer.on('lan:message', (_e, m) => cb(m)),
    onPeers: (cb) => ipcRenderer.on('lan:peers', (_e, ids) => cb(ids)),
  },
  together: {
    serve: (key, device) => ipcRenderer.invoke('tog:serve', { key, device }),
    stopServing: () => ipcRenderer.invoke('tog:serve:stop'),
    connect: (id, url, hello) => ipcRenderer.invoke('tog:connect', { id, url, hello }),
    close: (id) => ipcRenderer.invoke('tog:close', id),
    send: (to, text) => ipcRenderer.send('tog:send', { to, text }),
    onMessage: (cb) => ipcRenderer.on('tog:message', (_e, m) => cb(m)),
    onPeers: (cb) => ipcRenderer.on('tog:peers', (_e, ids) => cb(ids)),
    onClosed: (cb) => ipcRenderer.on('tog:closed', (_e, id) => cb(id)),
  },
  log: (level, source, message) => ipcRenderer.send('wave:log', { level, source, message }),
  openLogs: () => ipcRenderer.invoke('wave:logs:open'),
  onCommand: (cb) => ipcRenderer.on('wave:command', (_e, cmd) => cb(cmd)),
  takeLink: () => ipcRenderer.invoke('wave:link:take'),
  edit: (action) => ipcRenderer.send('wave:edit', action),
  onLink: (cb) => ipcRenderer.on('wave:link', (_e, link) => cb(link)),
  setPlayback: (state) => ipcRenderer.send('wave:playback', state),
  shellPrefs: () => ipcRenderer.sendSync('wave:shell:prefs'),
  setCloseToTray: (enabled) => ipcRenderer.send('wave:shell:close-to-tray', enabled),
  setAutostart: (enabled) => ipcRenderer.send('wave:shell:autostart', enabled),
  setDiscord: (enabled) => ipcRenderer.send('wave:shell:discord', enabled),
  setPresence: (track) => ipcRenderer.send('wave:discord', track),
  hotkeys: () => ipcRenderer.sendSync('wave:hotkeys:get'),
  setHotkeys: (next) => ipcRenderer.invoke('wave:hotkeys:set', next),
  pauseHotkeys: (on) => ipcRenderer.send('wave:hotkeys:pause', on),
  setProgress: (p) => ipcRenderer.send('wave:progress', p),
  openMini: () => ipcRenderer.send('wave:mini:open'),
  updateState: () => ipcRenderer.sendSync('wave:update:state'),
  onUpdate: (cb) => ipcRenderer.on('wave:update', (_e, s) => cb(s)),
  checkUpdate: () => ipcRenderer.send('wave:update:check'),
  installUpdate: () => ipcRenderer.send('wave:update:install'),
  openReleases: () => ipcRenderer.send('wave:update:releases'),
  // used by the mini player window
  miniCommand: (cmd) => ipcRenderer.send('wave:mini:command', cmd),
  miniReady: () => ipcRenderer.send('wave:mini:ready'),
  onPlayback: (cb) => ipcRenderer.on('wave:playback', (_e, s) => cb(s)),
  onProgress: (cb) => ipcRenderer.on('wave:progress', (_e, p) => cb(p)),
});
